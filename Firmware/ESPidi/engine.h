#ifndef ENGINE_H
#define ENGINE_H

#include <Arduino.h>

// Задача движка: MIDI-вход, такты (внутренние и внешние) и отправка MIDI. Работает с высоким
// приоритетом и просыпается каждые 0,5 мс по аппаратному таймеру, поэтому такты не ждут ни
// перерисовки экрана, ни чтения файлов в основном цикле.
//
// Состояние приложений общее для задачи движка и основного цикла. Всё, что его меняет или
// отправляет MIDI из основного цикла, выполняется под engine_lock(). Долгие операции (чтение
// файлов, вывод на экран) — вне блокировки.
void engine_begin();
void engine_lock();
void engine_unlock();

struct EngineLock {
    EngineLock() { engine_lock(); }
    ~EngineLock() { engine_unlock(); }
};

#endif
